import type { GeneratorPlugin } from '@open-mercato/shared/modules/generators'

function buildReportsDatasetsOutput({
  importSection,
  entriesLiteral,
}: {
  importSection: string
  entriesLiteral: string
}): string {
  return `// AUTO-GENERATED by mercato generate registry — do not edit
import type { Dataset } from '@open-mercato/shared/modules/reports/dsl'
${importSection ? `\n${importSection}\n` : '\n'}
type ReportsDatasetConfigEntry = { moduleId: string; datasets: Dataset[] }

const entriesRaw: ReportsDatasetConfigEntry[] = [
${entriesLiteral ? `  ${entriesLiteral}\n` : ''}]

const entries = entriesRaw.filter((e): e is ReportsDatasetConfigEntry => Array.isArray(e.datasets) && e.datasets.length > 0)

export const reportsDatasetConfigEntries = entries
export const allReportsDatasets: Dataset[] = entries.flatMap((e) => e.datasets)

const datasetsById = new Map(allReportsDatasets.map((d) => [d.id, d]))
export function getReportsDataset(id: string): Dataset | undefined {
  return datasetsById.get(id)
}
export function getReportsDatasetIds(): string[] {
  return Array.from(datasetsById.keys())
}
`
}

const reportsDatasetsPlugin: GeneratorPlugin = {
  id: 'reports.datasets',
  conventionFile: 'reports.ts',
  importPrefix: 'REPORTS_DATASETS',
  configExpr: (importName: string, moduleId: string) =>
    `{ moduleId: '${moduleId}', datasets: ((${importName}.datasets ?? ${importName}.default ?? []) as Dataset[]) }`,
  outputFileName: 'reports-datasets.generated.ts',
  buildOutput: buildReportsDatasetsOutput,
}

export const generatorPlugins: GeneratorPlugin[] = [reportsDatasetsPlugin]

export default generatorPlugins
